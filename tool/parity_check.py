#!/usr/bin/env python3
"""Method-parity checker: compares the public API of haveno-ts's HavenoClient.ts
against this package's lib/src/haveno_client.dart and writes PARITY.md.

Usage (from the repo root):

    python tool/parity_check.py [--ts path/to/HavenoClient.ts]

Defaults to ../haveno-ts/src/HavenoClient.ts relative to the repo root.
"""

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
DART_CLIENT = REPO / "lib" / "src" / "haveno_client.dart"
DEFAULT_TS = REPO.parent / "haveno-ts" / "src" / "HavenoClient.ts"
OUT = REPO / "PARITY.md"

KEYWORDS = {
    "if", "for", "while", "switch", "return", "catch", "else", "constructor",
    "new", "throw", "await", "super", "const", "let", "try", "case",
}


def ts_methods(src):
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    names = set()
    # class-body members (standard 2-space indent)
    for m in re.finditer(r"^  (?:static\s+)?(?:async\s+)?(?:readonly\s+)?([a-zA-Z_]\w*)\s*[(<]", src, re.M):
        if m.group(1) not in KEYWORDS:
            names.add(m.group(1))
    # methods with non-standard indentation (known: completeTrade at 4 spaces);
    # anchored on the async keyword so method-body lines can't false-positive
    for m in re.finditer(r"^\s{2,4}(?:static\s+)?async\s+([a-zA-Z_]\w*)\s*[(<]", src, re.M):
        names.add(m.group(1))
    return sorted(names)


def dart_methods(src):
    src = re.sub(r"//[^\n]*", "", src)
    names = set()
    for m in re.finditer(r"^  (?:static\s+)?[A-Za-z_][\w<>,?\[\]\s]*?\s([a-z_]\w*)\s*[(<]", src, re.M):
        names.add(m.group(1))
    return sorted(names)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ts", type=pathlib.Path, default=DEFAULT_TS)
    args = parser.parse_args()

    if not args.ts.exists():
        sys.exit(f"haveno-ts file not found: {args.ts}")
    if not DART_CLIENT.exists():
        sys.exit(f"Dart client not found: {DART_CLIENT}")

    ts = ts_methods(args.ts.read_text(encoding="utf-8"))
    dart = dart_methods(DART_CLIENT.read_text(encoding="utf-8"))

    missing = [m for m in ts if m not in dart]
    dart_only = [m for m in dart if m not in ts]

    lines = [
        "# Method parity: converge `HavenoClient.ts` (TypeScript) to `haveno_client.dart` (Dart)",
        "",
        "Generated by `python tool/parity_check.py` on 2026-10-17 "
        "(parses both source files with regexes; rerun after editing either side).",
        "",
        f"- HavenoClient.ts public methods detected: **{len(ts)}**",
        f"- haveno_client.dart methods detected: **{len(dart)}**",
        f"- Matched: **{len(ts) - len(missing)}/{len(ts)}**",
        f"- Missing in Dart: **{len(missing)}**",
        f"- Dart-only: **{len(dart_only)}**",
        "",
    ]

    if missing:
        lines += ["## Missing in Dart", ""] + [f"- `{m}`" for m in missing] + [""]
    else:
        lines += ["Every public method of `HavenoClient.ts` has a counterpart in `haveno_client.dart`.", ""]

    lines += ["## Dart-only methods", ""]
    notes = {
        "close": "Dart-specific: shuts down the gRPC channel so a Dart process can exit "
                 "(native gRPC keeps sockets open; haveno-ts relies on `disconnect()`).",
        "_onNotification": "private helper dispatching streamed notifications to local listeners.",
    }
    for m in dart_only:
        lines.append(f"- `{m}`" + (f" — {notes[m]}" if m in notes else ""))
    lines += [""]

    lines += ["## Full method list (both sides)", "", "| # | Method | In haveno-ts | In Dart |", "|---|---|---|---|"]
    for i, name in enumerate(sorted(set(ts) | set(dart)), 1):
        lines.append(f"| {i} | `{name}()` | {'yes' if name in ts else '—'} | {'yes' if name in dart else '—'} |")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT}")
    print(f"TS: {len(ts)} methods, Dart: {len(dart)}, missing: {missing}, dart-only: {dart_only}")


if __name__ == "__main__":
    main()
